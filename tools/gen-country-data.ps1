# Regenerates src\TimeZoneCalc.Core\CountryData.g.cs from Unicode CLDR:
#   - supplemental/windowsZones.xml : which countries use each Windows time zone
#   - cldr-json territories (zh-Hant, en) : country names
# Usage (PowerShell, from the repo root):
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\gen-country-data.ps1
param([string]$OutFile = "src\TimeZoneCalc.Core\CountryData.g.cs")

$ErrorActionPreference = "Stop"
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$base = "https://raw.githubusercontent.com/unicode-org"
$sources = @{
    zones = "$base/cldr/main/common/supplemental/windowsZones.xml"
    zh    = "$base/cldr-json/main/cldr-json/cldr-localenames-full/main/zh-Hant/territories.json"
    en    = "$base/cldr-json/main/cldr-json/cldr-localenames-full/main/en/territories.json"
}
$tmp = Join-Path ([IO.Path]::GetTempPath()) ("cldr-" + [Guid]::NewGuid().ToString("N"))
New-Item -ItemType Directory $tmp | Out-Null
try {
    foreach ($k in $sources.Keys) { Invoke-WebRequest -UseBasicParsing -Uri $sources[$k] -OutFile (Join-Path $tmp $k) }
    $zones = [xml](Get-Content -Raw -Encoding UTF8 (Join-Path $tmp "zones"))
    $zh = (Get-Content -Raw -Encoding UTF8 (Join-Path $tmp "zh") | ConvertFrom-Json).main.'zh-Hant'.localeDisplayNames.territories
    $en = (Get-Content -Raw -Encoding UTF8 (Join-Path $tmp "en") | ConvertFrom-Json).main.en.localeDisplayNames.territories
}
finally {
    Remove-Item -Recurse -Force $tmp
}

# All names for a territory code, including alternates such as "US-alt-short" = "US"
function Get-Names($table, [string]$code) {
    $table.PSObject.Properties | Where-Object { $_.Name -eq $code -or $_.Name -like "$code-alt-*" } | ForEach-Object { $_.Value }
}

$map = [ordered]@{}
foreach ($z in ($zones.supplementalData.windowsZones.mapTimezones.mapZone | Sort-Object other, territory)) {
    $code = [string]$z.territory
    if ($code -eq "001" -or $code -eq "ZZ") { continue }
    $id = [string]$z.other
    if (-not $map.Contains($id)) { $map[$id] = New-Object System.Collections.Generic.List[string] }
    foreach ($word in @(Get-Names $zh $code) + @(Get-Names $en $code) + @($code)) {
        if ($word -and -not $map[$id].Contains($word)) { $map[$id].Add($word) }
    }
}

function Escape([string]$s) { $s.Replace('\', '\\').Replace('"', '\"') }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// <auto-generated>")
[void]$sb.AppendLine("// Generated by tools\gen-country-data.ps1 from Unicode CLDR (windowsZones.xml + territory names). Do not edit.")
[void]$sb.AppendLine("// </auto-generated>")
[void]$sb.AppendLine("namespace TimeZoneCalc.Core;")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("internal static class CountryData")
[void]$sb.AppendLine("{")
[void]$sb.AppendLine("    // Windows time zone ID -> names (zh-Hant, en) and ISO codes of the countries that use it")
[void]$sb.AppendLine("    public static readonly IReadOnlyDictionary<string, string> Keywords = new Dictionary<string, string>")
[void]$sb.AppendLine("    {")
foreach ($id in $map.Keys) {
    [void]$sb.AppendLine("        [""$(Escape $id)""] = ""$(Escape (($map[$id]) -join ' '))"",")
}
[void]$sb.AppendLine("    };")
[void]$sb.AppendLine("}")

$full = Join-Path (Get-Location) $OutFile
[IO.File]::WriteAllText($full, $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
"Wrote $($map.Count) zones to $OutFile"
